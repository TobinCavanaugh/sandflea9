#!/usr/bin/env python3
"""
build/gen_ninja.py — generates build.ninja for sandfleaOS
Provides sub-second incremental builds with full GCC depfile tracking (-MMD -MF).
"""

import os
import sys

def main():
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    os.chdir(root_dir)

    c_sources = [
        "src/kernel/kern_asmstubs.c",
        "src/kernel/kern_compositor.c",
        "src/kernel/kern_ext2.c",
        "src/kernel/kern_fs.c",
        "src/kernel/kern_ide.c",
        "src/kernel/kern_ipc.c",
        "src/kernel/kern_interrupts.c",
        "src/kernel/kern_keyboard.c",
        "src/kernel/kern_mem.c",
        "src/kernel/kern_mouse.c",
        "src/kernel/kern_pci.c",
        "src/kernel/kern_sched.c",
        "src/kernel/kern_screen.c",
        "src/kernel/kern_serial.c",
        "src/kernel/kern_terminal.c",
        "src/kernel/kern_profile.c",
        "src/kernel/kern_tests.c",
        "src/kernel/quake.c",
        "src/kernel/kern_vmm.c",
        "src/kernel/libgcc_stubs.c",
        "src/kernel/main.c",
        "src/kernel/wasm_spawn.c",
        "src/kernel/wat2wasm_wrapper.c",
        "src/external/wasm-rt-impl.c",
        "src/external/wasm2c_wat2wasm.c",
        "src/external/xxhash/xxhash.c",
        "src/kernel/xhci/kern_xhci.c",
        "src/kernel/xhci/kern_xhci_rings.c",
        "src/kernel/xhci/kern_usb_hid.c",
        "src/kernel/ssfn.c",
        "src/kernel/stbsupport.c",
        "src/kernel/x64/idt.c",
        "src/kernel/x64/apic.c",
        "src/util/util_str.c",
        "src/util/util_cmd.c",
        "src/util/str_slice.c",
        "src/kernel/wasm3-0.5.0/source/m3_api_libc.c",
        "src/kernel/wasm3-0.5.0/source/m3_api_meta_wasi.c",
        "src/kernel/wasm3-0.5.0/source/m3_api_tracer.c",
        "src/kernel/wasm3-0.5.0/source/m3_api_uvwasi.c",
        "src/kernel/wasm3-0.5.0/source/m3_bind.c",
        "src/kernel/wasm3-0.5.0/source/m3_code.c",
        "src/kernel/wasm3-0.5.0/source/m3_compile.c",
        "src/kernel/wasm3-0.5.0/source/m3_core.c",
        "src/kernel/wasm3-0.5.0/source/m3_emit.c",
        "src/kernel/wasm3-0.5.0/source/m3_env.c",
        "src/kernel/wasm3-0.5.0/source/m3_exec.c",
        "src/kernel/wasm3-0.5.0/source/m3_function.c",
        "src/kernel/wasm3-0.5.0/source/m3_info.c",
        "src/kernel/wasm3-0.5.0/source/m3_module.c",
        "src/kernel/wasm3-0.5.0/source/m3_optimize.c",
        "src/kernel/wasm3-0.5.0/source/m3_parse.c",
    ]

    asm_sources = [
        "src/arch/kernel.asm",
        "src/arch/isrs.asm",
    ]

    ninja_lines = [
        "# build.ninja — generated by build/gen_ninja.py",
        "ninja_required_version = 1.8",
        "",
        "# Tools",
        "cc = gcc",
        "nasm = nasm",
        "ld = ld",
        "objcopy = objcopy",
        "",
        "# Flags",
        "cflags = -m64 -c -O3 -ffreestanding -nostdlib -g -nostdinc -fno-pic -fno-pie $",
        "         -mno-red-zone -mcmodel=kernel -I src/include -I src/external $",
        "         -I src/kernel/wasm3-0.5.0/source -D d_m3FixedHeap=false $",
        "         -Dd_m3SkipStackCheck=1 -D d_m3HasWASI=1 -Dd_m3VerboseErrorMessages=0 $",
        "         -ffast-math -DNDEBUG",
        "",
        "cflags_wasm2c = -m64 -c -O2 -fno-inline-functions -ffreestanding -nostdlib -g -nostdinc -fno-pic -fno-pie $",
        "                -mno-red-zone -mcmodel=kernel -I src/include -I src/external $",
        "                -I src/kernel/wasm3-0.5.0/source -D d_m3FixedHeap=false $",
        "                -Dd_m3SkipStackCheck=1 -D d_m3HasWASI=1 -Dd_m3VerboseErrorMessages=0 $",
        "                -ffast-math -DNDEBUG",
        "",
        "asmflags = -f elf64 -g",
        "ldflags = -m elf_x86_64 -T link.ld -build-id=none -z max-page-size=0x1000",
        "",
        "# Rules",
        "rule compile_c",
        "  depfile = $out.d",
        "  deps = gcc",
        "  command = $cc -MMD -MF $out.d $cflags $in -o $out",
        "  description = CC $in",
        "",
        "rule compile_c_wasm2c",
        "  depfile = $out.d",
        "  deps = gcc",
        "  command = $cc -MMD -MF $out.d $cflags_wasm2c $in -o $out",
        "  description = CC (wasm2c) $in",
        "",
        "rule compile_asm",
        "  command = $nasm $asmflags $in -o $out",
        "  description = NASM $in",
        "",
        "rule embed_font",
        "  command = $objcopy -I binary -O elf64-x86-64 -B i386:x86-64 $in $out",
        "  description = OBJCOPY $in",
        "",
        "rule link_kernel",
        "  command = $ld $ldflags -o $out $in",
        "  description = LINK $out",
        "",
        "rule build_filesystem",
        "  command = bash build/build_filesystem.sh",
        "  description = EXT2 FS",
        "",
        "rule package_iso",
        "  command = bash build/build_iso.sh",
        "  description = ISO $out",
        "",
    ]

    obj_files = []

    # ASM targets
    for asm_src in asm_sources:
        flat_name = asm_src.replace("/", "_").replace(".asm", "")
        out_obj = f"obj/{flat_name}.o"
        obj_files.append(out_obj)
        ninja_lines.append(f"build {out_obj}: compile_asm {asm_src}")

    # C targets
    for c_src in c_sources:
        flat_name = c_src.replace("/", "_").replace(".c", "")
        out_obj = f"obj/{flat_name}.o"
        obj_files.append(out_obj)
        if "wasm2c_wat2wasm.c" in c_src:
            ninja_lines.append(f"build {out_obj}: compile_c_wasm2c {c_src}")
        else:
            ninja_lines.append(f"build {out_obj}: compile_c {c_src}")

    # Font target
    font_obj = "obj/regularfont.o"
    obj_files.append(font_obj)
    ninja_lines.append(f"build {font_obj}: embed_font src/assets/regularfont.sfn")
    ninja_lines.append("")

    # Kernel ELF target
    obj_str = " ".join(obj_files)
    ninja_lines.append(f"build iso_root/kernel.elf: link_kernel {obj_str} | link.ld")
    ninja_lines.append("")

    # Filesystems
    ninja_lines.append("build iso_root/disk.img | data.img: build_filesystem")
    ninja_lines.append("")

    # ISO target
    ninja_lines.append("build sandfleaOS.iso: package_iso iso_root/kernel.elf iso_root/disk.img")
    ninja_lines.append("default sandfleaOS.iso")
    ninja_lines.append("")

    with open("build.ninja", "w", newline="\n") as f:
        f.write("\n".join(ninja_lines) + "\n")

    print(f"Generated build.ninja ({len(obj_files)} object targets).")

if __name__ == "__main__":
    main()
